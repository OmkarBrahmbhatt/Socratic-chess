def puzzle_slots(count, rating, shuffle=False):
    """Pick `count` puzzles for a rating, half forks and half pins.

    Puzzles are not repeated within a block unless the rating category has
    fewer puzzles of a theme than the block needs.
    """
    eligible = [
        puzzle_id
        for puzzle_id, puzzle in PUZZLES.items()
        if puzzle["rating_min"] <= rating <= puzzle["rating_max"]
    ]
    if not eligible:
        raise ValueError(f"No puzzles are configured for rating {rating}.")
    themes = {PUZZLES[puzzle_id]["theme"] for puzzle_id in eligible}
    if themes != {"Forks", "Pins"}:
        raise ValueError("Both fork and pin puzzles must be configured for each rating range.")
    slots = []
    for theme in ("Forks", "Pins"):
        matching = [puzzle_id for puzzle_id in eligible if PUZZLES[puzzle_id]["theme"] == theme]
        slots.extend(_draw(matching, count // 2))
    if count % 2:
        slots.append(random.choice(eligible))
    if shuffle:
        random.shuffle(slots)
    return slots


def _draw(pool, count):
    picks = []
    while len(picks) < count:
        picks.extend(random.sample(pool, min(len(pool), count - len(picks))))
    return picks
